// fluzer create 命令 / fluzer create command
//
// 职责：从模板创建全新的 Flutter 项目
// Responsibility: create a new Flutter project from the template

import 'dart:io';

import 'package:args/command_runner.dart';
import 'package:mason_logger/mason_logger.dart';
import 'package:path/path.dart' as p;

import '../config/project_config.dart';
import '../process/process_runner.dart';
import '../template/brick_loader.dart';
import '../template/brick_renderer.dart';
import '../template/template_source.dart';

/// 可注入的 flutter create 执行器，便于测试。
/// / Injectable flutter create runner for testability.
typedef CreateFlutterCreateRunner =
    Future<int> Function(
      String projectRoot, {
      String? projectName,
      String? org,
    });

/// 可注入的 flutter pub get 执行器，便于测试。
/// / Injectable flutter pub get runner for testability.
typedef CreateFlutterPubGetRunner = Future<int> Function(String projectRoot);

/// 可注入的 flutter gen-l10n 执行器，便于测试。
/// / Injectable flutter gen-l10n runner for testability.
typedef CreateFlutterGenL10nRunner = Future<int> Function(String projectRoot);

/// 可注入的 build_runner 执行器，便于测试。
/// / Injectable build_runner runner for testability.
typedef CreateBuildRunnerRunner = Future<int> Function(String projectRoot);

/// create 命令：从模板创建全新的 Flutter 项目。
///
/// 执行步骤：
/// 1. 校验项目名合法性
/// 2. 用 Mason 渲染 project brick 到当前目录（brick 的 `{{name}}` 层即目标项目目录）
/// 3. 执行 flutter create . --org --project-name
/// 4. 清理 flutter create 生成的多余测试文件
/// 5. 执行 flutter pub get
/// 6. 执行 flutter gen-l10n
/// 7. 执行 build_runner（可选）
///
/// create command: creates a new Flutter project from the template.
///
/// Steps:
/// 1. Validate project name
/// 2. Render the project brick via Mason into cwd (the brick's `{{name}}`
///    layer becomes the target project dir)
/// 3. Run flutter create . --org --project-name
/// 4. Clean up extra test files generated by flutter create
/// 5. Run flutter pub get
/// 6. Run flutter gen-l10n
/// 7. Run build_runner (optional)
class CreateCommand extends Command<int> {
  /// 创建 CreateCommand 实例。
  ///
  /// 所有执行器与 [loader] 均可注入，便于测试。
  ///
  /// Creates a CreateCommand instance.
  ///
  /// All runners and [loader] are injectable for testability.
  CreateCommand({
    Logger? logger,
    BrickLoader? loader,
    CreateFlutterCreateRunner? flutterCreate,
    CreateFlutterPubGetRunner? flutterPubGet,
    CreateFlutterGenL10nRunner? flutterGenL10n,
    CreateBuildRunnerRunner? buildRunner,
  }) : _logger = logger ?? Logger(),
       // ignore: prefer_initializing_formals
       _loader = loader,
       _flutterCreate = flutterCreate ?? _defaultFlutterCreate,
       _flutterPubGet = flutterPubGet ?? _defaultFlutterPubGet,
       _flutterGenL10n = flutterGenL10n ?? _defaultFlutterGenL10n,
       _buildRunner = buildRunner ?? _defaultBuildRunner {
    argParser.addOption(
      'org',
      defaultsTo: 'com.example',
      help: '组织标识（影响 bundle ID） / Organization identifier (affects bundle ID)',
    );
    argParser.addFlag(
      'build-runner',
      defaultsTo: true,
      negatable: true,
      help: '是否运行 build_runner / Whether to run build_runner after creation',
    );
  }

  final Logger _logger;
  final BrickLoader? _loader;
  final CreateFlutterCreateRunner _flutterCreate;
  final CreateFlutterPubGetRunner _flutterPubGet;
  final CreateFlutterGenL10nRunner _flutterGenL10n;
  final CreateBuildRunnerRunner _buildRunner;

  @override
  String get name => 'create';

  @override
  String get description =>
      '从模板创建全新 Flutter 项目 / Create a new Flutter project from the template';

  @override
  String get invocation => 'fluzer create <project_name>';

  @override
  Future<int> run() async {
    final projectName = argResults?.rest.firstOrNull;
    if (projectName == null) {
      _logger.err('错误：请指定项目名 / Error: please specify a project name');
      printUsage();
      return 1;
    }

    // 校验项目名合法性
    if (!_isValidProjectName(projectName)) {
      _logger.err(
        '项目名不合法：必须只包含小写字母、数字和下划线，且以字母开头。\n'
        'Invalid project name: must contain only lowercase letters, digits, '
        'and underscores, starting with a letter.',
      );
      return 1;
    }

    final org = argResults!['org'] as String;
    final runBuildRunner = argResults!['build-runner'] as bool;

    // 目标目录 = 当前工作目录 + 项目名（即 Mason 渲染出的 {{name}} 目录）
    final targetDir = p.join(Directory.current.path, projectName);

    try {
      _step('步骤 1/7：校验项目名 ...');
      _logger.detail('  项目名: $projectName, 组织: $org');

      // 检查目标目录是否已存在
      if (Directory(targetDir).existsSync()) {
        throw CliException(
          '目录 $projectName 已存在，请选择不同的项目名。\n'
          'Directory $projectName already exists. '
          'Please choose a different project name.',
        );
      }

      // 直接渲染到当前目录：brick 的 {{name}} 层展开后即为 targetDir，
      _step('步骤 2/7：用 Mason 渲染 project 模板 ...');
      final brickLoader =
          _loader ?? await TemplateSourceResolver(logger: _logger).resolve();
      final renderer = BrickRenderer(brickLoader);
      await renderer.generate(
        brickName: 'project',
        outputDir: Directory.current,
        vars: {'name': projectName},
      );
      _logger.detail('  已生成 $targetDir');

      _step('步骤 3/7：执行 flutter create . ...');
      await _runOrThrow(
        'flutter create',
        () => _flutterCreate(targetDir, projectName: projectName, org: org),
      );

      _step('步骤 4/7：清理 flutter create 生成的多余测试文件 ...');
      _cleanTests(targetDir);

      _step('步骤 5/7：执行 flutter pub get ...');
      await _runOrThrow('flutter pub get', () => _flutterPubGet(targetDir));

      _step('步骤 6/7：执行 flutter gen-l10n ...');
      await _runOrThrow('flutter gen-l10n', () => _flutterGenL10n(targetDir));

      _step('步骤 7/7：执行 build_runner ...');
      if (runBuildRunner) {
        final brExitCode = await _buildRunner(targetDir);
        if (brExitCode != 0) {
          _logger.warn(
            'build_runner 执行失败 (exit code: $brExitCode)，'
            '项目已创建，可手动运行。\n'
            'build_runner failed; project created. '
            'You can run it manually.',
          );
        }
      } else {
        _logger.info(
          '跳过 build_runner，可手动运行：\n'
          'Skipped build_runner; run it manually:\n'
          '  dart run build_runner build',
        );
      }

      _done(targetDir, projectName);
      return 0;
    } on CliException catch (e) {
      _logger.err(e.message);
      // 清理失败的目录
      _cleanupOnFailure(targetDir);
      return 1;
    } on ProcessException catch (e) {
      _logger.err(
        '未找到 Flutter 命令。请确保 Flutter SDK 已正确安装并在 PATH 中。\n'
        'Flutter command not found. Make sure Flutter SDK is installed and in PATH.\n'
        '原始错误 / Original error: ${e.message}',
      );
      _cleanupOnFailure(targetDir);
      return 1;
    } on Object catch (e) {
      _logger.err('创建失败 / Creation failed: $e');
      _cleanupOnFailure(targetDir);
      return 1;
    }
  }

  // ---------------------------------------------------------------------------
  // Helpers
  // ---------------------------------------------------------------------------

  /// 执行步骤命令并在非零退出码时抛出 [CliException]。
  ///
  /// [step] 为步骤名（自动拼入中英文错误信息），[runner] 为返回退出码的闭包
  /// （用闭包吞掉各 runner 签名差异，如 `flutter create` 额外带 name/org）。
  ///
  /// Runs a step command and throws [CliException] on a non-zero exit code.
  Future<void> _runOrThrow(String step, Future<int> Function() runner) async {
    final code = await runner();
    if (code != 0) {
      throw CliException(
        '$step 执行失败 (exit code: $code)\n'
        '$step failed (exit code: $code)',
      );
    }
  }

  /// 校验项目名是否合法（小写字母开头，只含小写字母、数字和下划线）。
  ///
  /// Validates that a project name is legal (starts with a lowercase letter,
  /// contains only lowercase letters, digits, and underscores).
  bool _isValidProjectName(String name) {
    final regex = RegExp(r'^[a-z][a-z0-9_]*$');
    return regex.hasMatch(name);
  }

  /// 打印步骤标题 / Prints a step header
  void _step(String message) {
    _logger.info('\n$message');
  }

  /// 打印完成信息 / Prints completion message
  void _done(String targetDir, String projectName) {
    _logger.success('\n项目创建完成！ / Project created successfully!');
    _logger.info('');
    _logger.info('后续步骤 / Next steps:');
    _logger.info('  1. cd $projectName');
    _logger.info('  2. fluzer new my_feature （可选：添加功能模块）');
    _logger.info('  3. flutter run           （启动应用）');
  }

  /// 清理 flutter create 生成的多余测试文件。
  ///
  /// `flutter create .` 会自动在 test/ 目录下生成一个默认的
  /// `widget_test.dart`，但模板项目已自带了 `home_page_test.dart`，
  /// 该默认测试文件需要删除。
  ///
  /// Cleans up extra test files generated by `flutter create .`.
  ///
  /// `flutter create .` auto-generates a default `widget_test.dart`
  /// in the test/ directory, but the template already includes
  /// `home_page_test.dart`. This default test file should be removed.
  void _cleanTests(String targetDir) {
    final widgetTest = File(p.join(targetDir, 'test', 'widget_test.dart'));
    if (widgetTest.existsSync()) {
      widgetTest.deleteSync();
      _logger.detail('  已删除 / Removed: test/widget_test.dart');
    }
  }

  /// 创建失败时清理目标目录。
  ///
  /// Cleans up the target directory on failure.
  void _cleanupOnFailure(String targetDir) {
    final dir = Directory(targetDir);
    if (dir.existsSync()) {
      try {
        dir.deleteSync(recursive: true);
        _logger.detail('  已清理失败目录 / Cleaned up failed directory');
      } on Object {
        // 清理失败不影响错误报告
      }
    }
  }

  // ---------------------------------------------------------------------------
  // Default runners
  // ---------------------------------------------------------------------------

  /// 默认的 flutter create 执行器 / Default flutter create runner
  static Future<int> _defaultFlutterCreate(
    String projectRoot, {
    String? projectName,
    String? org,
  }) {
    final args = ['create', '.'];
    if (projectName != null) {
      args.addAll(['--project-name', projectName]);
    }
    if (org != null) {
      args.addAll(['--org', org]);
    }
    return ProcessRunner.run('flutter', args, workingDirectory: projectRoot);
  }

  /// 默认的 flutter pub get 执行器 / Default flutter pub get runner
  static Future<int> _defaultFlutterPubGet(String projectRoot) {
    return ProcessRunner.run('flutter', [
      'pub',
      'get',
    ], workingDirectory: projectRoot);
  }

  /// 默认的 flutter gen-l10n 执行器 / Default flutter gen-l10n runner
  static Future<int> _defaultFlutterGenL10n(String projectRoot) {
    return ProcessRunner.run('flutter', [
      'gen-l10n',
    ], workingDirectory: projectRoot);
  }

  /// 默认的 build_runner 执行器 / Default build_runner runner
  static Future<int> _defaultBuildRunner(String projectRoot) {
    return ProcessRunner.run('dart', [
      'run',
      'build_runner',
      'build',
    ], workingDirectory: projectRoot);
  }
}
